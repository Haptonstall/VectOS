/**
 * Typed keys for section citations within a BuildingCode.
 * Values are citation strings, e.g. "IBC 2024 Section 1604.3"
 */
enum class CodeReferenceKey {
    LOAD_COMBINATIONS,
    DEFLECTION_LIMITS_TABLE,
    RISK_CATEGORY_DEFINITIONS,
    SERVICEABILITY_CRITERIA,
    LIVE_LOAD_REDUCTION
}